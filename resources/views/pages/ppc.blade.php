                                <h2 class="border-b font-cinzel w-full text-2xl">What the PPC Does</h2>
                                <p>The St. Emile Parish Pastoral Council (PPC) is a consultative body which assists and advises the pastor.  It is the main body for lay leadership in the pastoral life of our parish.  It exists to foster pastoral activity which is in accord with and expresses the mission of the parish.  It aims to engage and enable the whole parish community for fuller participation in the mission of the parish.  The PPC maintains good communication between all other parish groups.</p>
                                <p class="ml-4 italic">
                                    "Together we strive to live out the full mission of the Church sharing the Good News of Jesus Christ and building up his reign of justice, mercy, love and peace. In all of this, it is increasingly clear that in a parish, the two key sources and prime movers of all this are the Pastors, Parish Life Directors and the Parish Pastoral Council (surrounded and carried by all the faithful)."
                                </p>
                                <p class="ml-4">-- Archbishop Albert LeGatt --</p>
