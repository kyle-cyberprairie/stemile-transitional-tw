                        <x-accordion id="a1" title="General Information">
                            <p>There are many different ministries and organizations at work in St. Emile Parish.  The simplest way to become involved in a particular activity or organization is to email the office at <a href="mailto:st-emile@shaw.ca">st-emile@shaw.ca</a></p>
                        </x-accordion>
                        <x-accordion id="a2" title="Faith and Spiritual Growth">
                            <p>
                                The Faith and Spiritual Growth Ministry is engaged in providing opportunities for faith and spiritual growth in the parish.  This ministry seeks, with the guidance of the Holy Spirit, to reach out to parishioners, wherever they are in their spiritual journey, to offer varied forms of informative and enriching opportunities to gather where they may encounter Christ and share His love with others.
                            </p>
                            <p>
                                Members of this ministry venture into opportunities of growth and of challenge, being strengthened alongside their brothers and sisters.  They are committed to frequent prayer for St. Emile and all its needs.  They practice ‘listening’ prayer so that they may learn to discern their path.
                            </p>
                            <p>
                                Past initiatives have included:
                            </p>
                            <ul class="list-disc list-inside">
                                <li>a nine-part video series by Father Bob Bedard</li>
                                <li>Lenten Scripture study</li>
                                <li>varied book studies/sharing groups</li>
                                <li>a 10-part live presentation on prayer</li>
                                <li>Advent book study and meditation</li>
                                <li>a parish-wide invitation to pray the Novena to the Holy Spirit.</li>
                            </ul>
                            <p>New members are always welcome!  In addition, the Faith and Spiritual Growth Ministry is always seeking suggestions from parishioners for future projects.</p>
                        </x-accordion>
                        <x-accordion id="a3" title="Finance Committee">
                            <p>
                                “This committee has a responsibility distinct from those of the Parish Pastoral Council (PPC) and functions autonomously from it.” (Guidelines from Diocese)   A representative sits on the Parish Pastoral Committee, (PPC).
                            </p>
                            <p>
                                This committee is made up of a minimum of five parish members.
                            </p>
                            <p>
                                Responsibilities:
                            </p>
                            <ul class="list-disc list-inside">
                                <li>Administer the funds of the parish.</li>
                                <li>Maintain all facilities belonging to the parish (church, yard, four-plex).</li>
                                <li>Pay wages.</li>
                                <li>Inform parishioners of audit and balance of books at Annual General Meeting (AGM).</li>
                                <li>Report on projects and finances at PPC meetings.</li>
                                <li>Inform parishioners as to projects and or needs.</li>
                                <li>A complete Financial Report is included in the AGM booklet with the Chairperson and Office accountant presenting and on hand to answer questions from parishioners.</li>
                            </ul>
                        </x-accordion>
                        <x-accordion id="a4" title="Food Bank">
                            <p>
                                The St. Emile food bank provides service from the parish centre and operates in association with Winnipeg Harvest.  Ten to twelve volunteers provide the service and approximately 60 to 85 families are served.  Food items are provided by Winnipeg Harvest and donations from parishioners.  Additional food supplies are purchased with donated monies.
                            </p>
                        </x-accordion>
                        <x-accordion id="a5" title="Hospitality">
                            <p>
                                The goals of the hospitality ministry are:
                            </p>
                            <ul class="list-disc list-inside">
                                <li>to present meaningful opportunities for parishioners to become better acquainted and to get to know each other by name,</li>
                                <li>to welcome newcomers and visitors to St. Emile and help them find friends and support groups in the parish community, and</li>
                                <li>to build confidence and a sense of belonging in parishioners, newcomers, and visitors by encouraging them to get involved in the parish community.</li>
                            </ul>
                            <p>The hospitality committee hosts a coffee and fellowship event once a month after the 9 a.m. Mass.  Volunteers are needed not only to host the fellowship events, but also to bake and shop for provisions.</p>
                        </x-accordion>
                        <x-accordion id="a6" title="Knights of Columbus">
                            <p>
                                The Knights of Columbus are Catholic men who are committed to making our community a better place while supporting our parish family in many different ways--volunteering their time, supporting the Catholic Church and its causes, protecting and enhancing their family lives--and all the while, deepening their own faith.
                            </p>
                        </x-accordion>
                        <x-accordion id="a7" title="Legion of Mary">
                            <p>
                                Members meet every Thursdays after 9:30 am mass in the Parish Centre. Members visit the sick in homes, hospitals, and nursing and seniors’ homes, and also distribute religious articles and provide pastoral and communion services there.  In addition to assisting in cleaning in the church and chapel, members hold Holy two hours every year on February 28 in the chapel and deliver the pilgrim statue of the Blessed Virgin Mary and the enthronement of the Sacred Heart of Jesus to homes in our community.
                            </p>
                        </x-accordion>
                        <x-accordion id="a8" title="Liturgical Hosting (Greeting, Offertory, Collection)">
                            <p>
                                The Liturgical Hosting Ministry is a group of parishioners who:
                            </p>
                            <ul class="list-disc list-inside">
                                <li>serve as Greeters,</li>
                                <li>take up the Collection, and</li>
                                <li>carry the Offertory gifts</li>
                            </ul>
                            <p>at the three week-end Masses as well as Ash Wednesday, Easter, and Christmas Masses. This ministry is part of the Liturgy Ministry and both work closely together.  Hosts can serve individually or serve as a couple or a family.</p>
                        </x-accordion>
                        <x-accordion id="a9" title="Liturgical Ministry (Lectors and Communion Ministers)">
                            <p>
                                Liturgical ministry strives to strengthen, enrich, and nurture a positive culture among ministers  serving as lectors and/or eucharistic ministers in order to enhance the experience of the people of God as they come together to pray, to reflect, to learn, and celebrate. Training sessions are offered twice per year. 
                            </p>
                        </x-accordion>
                        <x-accordion id="a10" title="Maintenance">
                            <p>
                                Our Caretaker, Ed Lazarko, is responsible for taking care of the facilities, doing necessary repairs, coordinating volunteer helpers, having back-up plans in place, and preparing for the future.
                            </p>
                            <p>
                                 Ed oversees the upkeep and necessary renovations of the church, parish centre and adjoining four-plex building.  Major renovations have included replacing the boiler in the church, replacing shingles on the church, parish centre and rectory, renovating the church washroom, installing air conditioner system in the church, updating electrical and more.
                            </p>
                            <p>
                                 We also have some volunteers who give their time to some of the cleaning of the church, helping to set up for events and activities and looking after the flowerbeds on the property.  If you are interested in helping out in the maintenance department, please contact the office at 
                                 <a href="mailto:st-emile@shaw.ca">st-emile@shaw.ca</a>.
                            </p>
                        </x-accordion>
                        <x-accordion id="a11" title="Music">
                            <p>
                                This ministry is comprised of a group of parishioners who come together to share their musical talent and time to ensure the sequence of the Masses flows seamlessly.  All elements of the Mass including the music form a complete and organic harmony, clearly expressive of the unity of the body of Christ, the Church. The functionality and beauty of the Mass and all the music foster devotion and remind us of the holiness of the mysteries celebrated.  The Music Ministry always welcomes new members: singers, musicians, and PowerPoint authors and operators. 
                            </p>
                        </x-accordion>
                        <x-accordion id="a12" title="Pastoral Care for the Sick and Shut-ins">
                            <p>
                                This ministry is based on identifying and meeting the needs of the sick, shut-in, and lonely people of our parish by providing visits, prayer and Holy Communion.  Our goal is to share our faith by action and love and to bring a little extra joy into their lives.
                            </p>
                            <p>
                                 Volunteers visit and take Holy Communion to the homes of parishioners who are unable to attend Mass through age or illness.  They always make their visits in pairs. 
                            </p>
                        </x-accordion>
                        <x-accordion id="a13" title="Sacristy">
                            <p>
                                The Sacristy Ministry makes liturgical preparations for all masses:   prepares the linens, sets up and cleans up after masses, prepares the schedules for volunteers for the weekday masses in the chapel, and assists at funeral services and baptisms.
                            </p>
                            <p>
                                Do you have a bit of time to offer?  Does this ministry interest you?  Your help can be as simple as offering to wash the linens or water the plants!  Be as involved as you wish!
                            </p>
                        </x-accordion>
                        <x-accordion id="a14" title="Youth">
                            <p>
                                The Youth Ministry is committed to forming intentional disciples of Christ through evangelization, local community efforts/outreach, and through fellowship and faith-sharing.  The Youth Ministry aims to provide a place for fellowship, guidance and faith formation for the young people of our parish--a place where each one can feel that they belong and are welcome, where each person has a place to discover and use their individual gifts, learning to use them in the context of the church, for the greater good and the glory of God.
                            </p>
                            <p>
                                 Any inquiries to the Youth Group can be directed to 
                                 <a href="mailto:st.emile.youth@gmail.com">st.emile.youth@gmail.com</a>.
                            </p>
